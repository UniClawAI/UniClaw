"""内置 Skill: 代码审查"""

from uniclaw.tools.skill.loader import SkillDef, register_builtin

_CODE_REVIEW_PROMPT = r"""## 代码审查

对指定目标进行多维度代码审查。

### 目标

如果用户指定了参数,审查该目标(文件路径、PR 编号等)。
否则审查当前未提交的变更:先运行 `git diff --cached`,如果没有暂存内容则运行 `git diff`。

如果 diff 为空,告知用户没有可审查的变更并结束。

### 审查维度

按以下维度逐一分析,每个维度独立评估:

1. **🔒 安全性**
   - SQL 注入、XSS、命令注入、路径遍历
   - 敏感信息硬编码(密钥、密码、token)
   - 权限检查缺失、输入校验不足

2. **🐛 正确性**
   - 边界条件未处理(空值、空列表、溢出)
   - 逻辑错误、条件反转
   - 异常处理缺失或不当
   - 并发安全问题

3. **⚡ 性能**
   - 不必要的循环或重复计算
   - N+1 查询模式
   - 大对象未释放、内存泄漏风险
   - 可缓存但未缓存的计算

4. **🧹 代码质量**
   - 命名不清晰、不符合项目惯例
   - 代码重复、可提取为公共函数
   - 函数过长、职责不单一
   - 魔法数字、硬编码字符串

5. **📖 可读性**
   - 缺少必要注释(复杂逻辑、非显而易见的设计决策)
   - 抽象层次不一致
   - 控制流过深(嵌套 if/for)

### 输出格式

```
## 📋 代码审查报告

**审查范围**: [描述审查了什么]
**变更文件数**: N
**变更行数**: +N / -N

### 发现的问题

按严重程度排序:

🔴 **严重** — 必须修复
- [文件:行号] 问题描述
  > 修复建议: ...

🟡 **警告** — 建议修复
- [文件:行号] 问题描述
  > 修复建议: ...

🔵 **建议** — 可选改进
- [文件:行号] 问题描述
  > 修复建议: ...

### 总结

[一句话总结变更质量和主要风险]
```

### 注意事项

- 只报告**实际存在的问题**,不要猜测或列出"可能"的问题
- 如果代码质量很好,直接说"未发现明显问题"
- 不要审查未变更的代码
- 对于大型 diff(>500 行),重点关注变更部分,不要逐行审查"""


def register():
    """注册 code-review 技能"""
    register_builtin(
        SkillDef(
            name="code-review",
            description="审查代码变更,检查安全性、正确性、性能、代码质量和可读性问题。"
            "当用户要求审查代码、检查变更、review diff 时使用。"
            "支持审查当前未提交的变更、指定文件或 PR。",
            triggers=["/code-review", "/review", "code-review"],
            tools=["Bash", "Read", "Grep"],
            prompt=_CODE_REVIEW_PROMPT,
            file_path=__file__,
            source="builtin",
            when_to_use="用户要求审查代码、检查变更、review、找 bug、安全检查时",
            argument_hint="[文件路径或 PR 编号]",
        )
    )
