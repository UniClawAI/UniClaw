"""内置 Skill: 记忆管家"""

from uniclaw.tools.skill.loader import SkillDef, register_builtin

_MEMORY_ORGANIZE_PROMPT = r"""## 记忆管家

整理和优化记忆系统,从会话中提取有价值的内容。

### 任务概述

根据用户参数决定执行哪些任务。如果参数为空或包含"all",执行全部任务。

可选任务:
1. **整理记忆** — 合并重复、删除过时
2. **会话挖掘** — 从最近会话提取有价值内容

**参数示例**:
- `all` 或空: 执行所有任务
- `整理`: 只整理记忆
- `挖掘`: 只挖掘会话
- `整理 挖掘`: 整理记忆 + 挖掘会话

---

### 任务 1: 整理记忆

**目标**: 清理记忆库,合并重复内容,删除过时信息。

**步骤**:

1. **加载所有记忆**
   - 使用 `memory_list(scope="all")` 获取完整记忆列表
   - 记录每条记忆的名称、描述、类型、置信度

2. **识别重复记忆**
   - 分析记忆列表,找出描述相似或内容相关的记忆
   - 重点关注:
     - 名称相似的记忆(如"用户偏好-代码风格"和"代码规范")
     - 描述相近的记忆
     - 内容有重叠的记忆

3. **合并重复记忆**
   - 对于重复记忆,保留最完整、最新的版本
   - 合并时保留所有有价值的信息
   - 使用 `memory_save(name=..., description=..., content=..., scope=..., type=..., force=True)` 覆盖
   - 使用 `memory_delete(name=..., scope=...)` 删除被合并的记忆

4. **识别过时记忆**
   - 检查记忆的置信度(confidence < 0.7 的需要关注)
   - 检查记忆的来源(source="model" 的可能需要验证)
   - 检查记忆内容是否与当前项目状态不符

5. **删除过时记忆**
   - 对于明显过时或错误的记忆,直接删除
   - 对于可能过时但不确定的记忆,降低置信度而非删除

**输出格式**:
```
## 📋 记忆整理报告

### 合并的记忆
- [原记忆A] + [原记忆B] → [合并后记忆]
  - 合并原因: ...
  - 保留内容: ...

### 删除的记忆
- [记忆名称]
  - 删除原因: ...

### 保留的记忆
- 共 N 条记忆保持不变

### 整理统计
- 合并: N 组
- 删除: N 条
- 保留: N 条
```

---

### 任务 2: 会话挖掘

**目标**: 从最近会话中提取有价值的内容,转化为长期记忆。

**步骤**:

1. **加载最近会话**
   - 使用 `session_list(limit=10)` 获取最近 10 个会话
   - 重点关注最近 3-5 个会话

2. **分析会话内容**
   对每个会话,使用 `session_detail(session_id=...)` 查看完整内容,寻找:

   a. **错误和解决方案**
   - 命令执行失败的原因
   - 如何避免类似错误
   - 正确的替代方案

   b. **用户偏好**
   - 用户喜欢的代码风格
   - 用户习惯的工作流程
   - 用户对工具的偏好

   c. **项目知识**
   - 项目特定的配置要求
   - 项目的工作流程
   - 项目的约定和规范

   d. **技术洞察**
   - 有效的解决方案
   - 性能优化技巧
   - 最佳实践

3. **检查已有记忆**
   使用 `memory_search` 搜索相关记忆,判断:
   - 是否已存在相同或相似的记忆?
   - 已有记忆是否需要更新或补充?

4. **处理发现的内容**

   a. **如果记忆不存在** → 创建新记忆
   - 使用 `memory_save` 保存:
   - name: 描述性名称,便于检索
   - description: 简短说明
   - content: 详细内容,包含上下文和应用方法
   - type: 根据内容选择(user/feedback/project/reference)
   - scope: 根据适用范围选择(user/project)
   - confidence: 根据确定程度设置(0.7-1.0)
   - source: "model"(由AI提取)

   b. **如果记忆已存在但需要补充** → 更新已有记忆
   - 使用 `memory_save` 并设置 `force=True` 覆盖
   - 保留原有内容,添加新发现的信息
   - 在内容末尾添加"补充"章节
   - 示例:
     ```
     [原有内容...]

     ## 补充 (YYYY-MM-DD)
     [新发现的信息]
     ```

   c. **如果记忆已存在且完整** → 跳过
   - 不做任何操作,避免重复

**输出格式**:
```
## 🔍 会话挖掘报告

### 分析的会话
1. [会话标题] (N条消息)
2. ...

### 新增的记忆

#### 错误和解决方案
- [记忆名称]
  - 来源: [会话标题]
  - 内容摘要: ...

#### 用户偏好
- [记忆名称]
  - 来源: [会话标题]
  - 内容摘要: ...

#### 项目知识
- [记忆名称]
  - 来源: [会话标题]
  - 内容摘要: ...

### 更新的记忆

- [记忆名称]
  - 更新原因: 补充了新的信息
  - 新增内容: ...

### 跳过的记忆(已存在且完整)

- [记忆名称]
  - 原因: 内容已完整,无需更新

### 挖掘统计
- 分析会话: N 个
- 新增记忆: N 条
- 更新记忆: N 条
- 跳过(已存在): N 条
```

---

### 综合执行策略

当执行全部任务时,按以下顺序执行:

1. **先整理记忆** — 清理重复和过时内容
2. **再挖掘会话** — 提取新内容

这样可以避免:
- 在整理前保存可能重复的内容
- 遗漏有价值的信息

### 注意事项

- **避免重复**: 保存前必须检查是否已存在相似记忆,使用 `memory_search` 搜索
- **允许更新**: 如果已有记忆需要补充,可以使用 `force=True` 更新,保留原有内容
- **保守原则**: 不确定是否值得保存的内容,宁可不保存
- **用户优先**: 用户明确要求保存的内容,即使价值不高也保存
- **保持简洁**: 记忆内容应该精炼,避免冗长
- **标注来源**: 记录内容的来源,便于追溯和验证
- **设置置信度**: 根据确定程度设置合理的置信度"""


def register():
    """注册 memory-organize 技能"""
    register_builtin(
        SkillDef(
            name="memory-organize",
            description="记忆管家:整理记忆系统,从会话中提取有价值内容。"
            "当用户要求整理记忆、优化记忆、清理记忆、挖掘会话、记忆管理时使用。",
            triggers=["/memory-organize", "/organize-memory", "/memory-clean", "memory-organize"],
            tools=["Bash", "Read", "Write", "Glob", "memory_save", "memory_delete", "memory_list", "memory_search", "session_list", "session_detail"],
            prompt=_MEMORY_ORGANIZE_PROMPT,
            file_path=__file__,
            source="builtin",
            when_to_use="用户要求整理记忆、优化记忆、清理记忆、挖掘会话、记忆管理时",
            argument_hint="[all/整理/挖掘]",
        )
    )
